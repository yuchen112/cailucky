export function createDialoguePicker(random=Math.random) {
  const remaining=new Map(), previous=new Map();
  return id=>{
    const lines=heroDialogue[id];
    if(!lines?.length)return null;
    let bag=remaining.get(id);
    if(!bag?.length){
      bag=[...lines];
      for(let i=bag.length-1;i>0;i--){const j=Math.floor(random()*(i+1));[bag[i],bag[j]]=[bag[j],bag[i]];}
      if(bag.at(-1)===previous.get(id))[bag[0],bag[bag.length-1]]=[bag.at(-1),bag[0]];
      remaining.set(id,bag);
    }
    const line=bag.pop();previous.set(id,line);return line;
  };
}
