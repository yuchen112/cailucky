import assert from 'node:assert/strict';
import {validateCampaignProgress} from '../games/fairytale-defense/rebuild/campaign-progress.mjs';
const catalog=Array.from({length:20},(_,i)=>({id:`stage-${i+1}`}));
const legacy={unlocked:16,cleared:Array.from({length:15},(_,i)=>i+1)};
const snapshot=JSON.stringify(legacy);
const migrated=validateCampaignProgress(legacy,catalog);
assert.equal(migrated.unlockedId,'stage-16');
assert.equal(migrated.clearedIds.length,15);
assert.equal(JSON.stringify(legacy),snapshot);
const reordered=[catalog[1],catalog[0],...catalog.slice(2)];
assert.deepEqual(validateCampaignProgress({clearedIds:['stage-1']},reordered).cleared,[2]);
assert.equal(validateCampaignProgress({clearedIds:['stage-1']},reordered).unlockedId,'stage-2');
const inserted=[{id:'new-opening'},...catalog];
const expanded=validateCampaignProgress(migrated,inserted);
assert.equal(expanded.unlockedId,'new-opening');
assert.equal(expanded.clearedIds.length,15);
assert.equal(validateCampaignProgress({clearedIds:catalog.map(s=>s.id)},catalog).unlocked,20);
assert.throws(()=>validateCampaignProgress({clearedIds:['missing']},catalog));
assert.throws(()=>validateCampaignProgress({clearedIds:['stage-1','stage-1']},catalog));
assert.throws(()=>validateCampaignProgress({clearedIds:[]},[{id:'duplicate'},{id:'duplicate'}]));
console.log('PASS: 20-stage catalog, legacy migration, stable IDs across reordered/inserted stages, immutable inputs and invalid ID rejection.');
